"""Behavior view contracts; fixture counts are independent of detector code."""
from copy import deepcopy
import json
import unittest

from true_rl_agent.tasks.stair_climbing.behavior import (
    LEGACY_FULL_SCHEMA as FULL_SCHEMA, LEGACY_PUBLIC_SCHEMA, PREVIOUS_PUBLIC_SCHEMA as PUBLIC_SCHEMA,
    LEGACY_RULE_VERSION as RULE_VERSION,
    FULL_SCHEMA as MOTION_FULL_SCHEMA, PUBLIC_SCHEMA as MOTION_PUBLIC_SCHEMA,
    RULE_VERSION as MOTION_RULE_VERSION,
    MAX_PUBLIC_BYTES, project_stair_behavior, compare_stair_behavior,
)


def episode(index, *, reason="forbidden_contact", cell="z-main", run=0):
    return {"episode_id": f"r{run}.e{index}", "run": run, "slot": index,
        "cell": cell, "stratum": "frontier", "primary_reason": reason,
        "steps": 100, "dt_s": .02, "anchor": {"status": "crossed", "step": 10},
        "ranges": {"roll_rad": [0., .8], "pitch_rad": [0., .2], "progress_m": [0., 1.]},
        "body_extrema": [["foot", .01, .7, .1]],
        "events": [
            {"code": "low_progress", "body": "root", "start": 20, "end": 90, "confirmed": 20},
            {"code": "tilt", "body": "root", "start": 70, "end": 100, "confirmed": 79},
            *[{"code": "slip_body", "body": f"foot{i}", "start": 91+i, "end": 91+i, "confirmed": None} for i in range(8)],
        ],
        "before_terminal": {"tilt": True, "slip_any": False, "low_clearance_any": False, "low_progress": True},
        "window_present": {"tilt": True, "slip_any": True, "low_clearance_any": False, "low_progress": True},
        "coverage": {"first_step": 1, "last_step": 100, "window_first_step": 51, "terminal_included": True}}


def full(episodes):
    return {"schema_version": FULL_SCHEMA,
        "domain": {**{key: "a"*64 for key in ("checkpoint_hash", "task_protocol_hash", "suite_hash",
            "projection_hash", "source_hash", "cohort_hash", "episode_keys_hash", "reward_input_schema_hash", "archive_hash")},
            "rule_version": RULE_VERSION, "numeric_profile": "fixture.v1", "history_status": "recorded"},
        "semantics": {"kinematic_body": "root", "support_bodies": ["foot"], "forbidden_bodies": ["body"],
            "thresholds": {"slip_mps": .5, "slip_steps": 5, "contact_N": 1., "tilt_rad": .65,
                           "tilt_steps": 10, "clearance_m": .018, "clearance_steps": 3},
            "actionability": {"slip_any": ["instant_only"], "slip_body": ["instant_only"]}},
        "episodes": episodes, "summary_hash": "b"*64}


def legacy_view():
    # Explicit saved-v1 layout, not generated by the production v2 projection.
    value = project_stair_behavior(full([episode(0)]))
    value["schema_version"] = LEGACY_PUBLIC_SCHEMA
    columns = ["stratum", "primary_reason", "n", "root_anchor_crossed", "tilt", "slip_any",
               "low_clearance_any", "low_progress", "min_steps", "max_steps", "window_tilt",
               "window_slip_any", "window_low_clearance_any", "window_low_progress"]
    value["profile"] = {"episode_count": 1, "columns": columns,
        "indexed_labels": {"stratum": ["frontier"], "primary_reason": ["forbidden_contact"]},
        "event_count_scope": "saved v1 count definition", "rows": [[0, 0, 1, 1, 1, 0, 0, 1, 100, 100, 1, 1, 0, 1]]}
    value["contrasts"] = {"matched_cell_run_count": 0, "all_cell_run_count": 1,
        "columns": [], "rows": [], "missing_group_count": 1, "scope": "saved v1"}
    value["omitted"]["contrast_rows"] = 0
    for transcript in value["transcripts"]:
        transcript.pop("omitted_body_extrema")
    return value


def motion_full(episodes):
    value = full(deepcopy(episodes))
    value["schema_version"] = MOTION_FULL_SCHEMA
    value["domain"]["rule_version"] = MOTION_RULE_VERSION
    value["semantics"]["rules"] = {"unloaded_low_motion": "same-body unloaded speed<=0.05 for 0.5s"}
    for row in value["episodes"]:
        row["before_terminal"]["unloaded_low_motion"] = False
        row["root_motion"] = {"first": [0., 0., 0., 1.], "last": [.8, .8, -.2, .67],
            "extrema": {"x_m": [0., 1, 1., 80], "roll_rad": [0., 1, .8, 90],
                        "pitch_rad": [-.2, 90, .1, 70], "up_z": [.67, 90, 1., 1]},
            "max_x_retreat": [80, 100, .2], "first_up_z_negative_step": None}
    return value


class StairProjectionRevisionTests(unittest.TestCase):
    def test_dominant_reason_pair_is_not_lexicographic_and_counts_do_not_mix_reasons(self):
        episodes = [episode(0, reason="timeout", cell="a-rare")]
        episodes += [episode(i) for i in range(1, 6)]
        episodes += [episode(i, reason="success") for i in range(6, 8)]
        episodes += [episode(8, reason="timeout")]
        value = project_stair_behavior(full(episodes))
        self.assertEqual(value["schema_version"], PUBLIC_SCHEMA)
        self.assertEqual(value["transcripts"][0]["cell"], "z-main")
        self.assertEqual(value["transcripts"][1]["relationship"], "same_cell_run")
        core = value["contrasts"]["rows"][0]
        self.assertEqual((core["reason"], core["failed"]["n"], core["success"]["n"]), ("forbidden_contact", 5, 2))
        self.assertEqual(core["failed"]["confirmed"]["tilt"], 5)
        self.assertEqual(value["profile"]["episode_count"], 9)
        self.assertEqual(project_stair_behavior(value), value)
        self.assertEqual(project_stair_behavior(full(list(reversed(episodes)))), value)

    def test_missing_match_is_explicit_and_does_not_borrow_an_unrelated_success(self):
        value = project_stair_behavior(full([episode(0), episode(1, reason="success", cell="other")]))
        self.assertEqual(len(value["transcripts"]), 1)
        row = value["contrasts"]["rows"][0]
        self.assertEqual(row["status"], "missing_same_cell_run_success")
        self.assertEqual(row["success"]["n"], 0)
        self.assertIn("not a zero rate", value["contrasts"]["scope"])

    def test_view_keeps_process_intervals_and_narrows_proxy_names(self):
        source = full([episode(0), episode(1, reason="success")])
        before = deepcopy(source)
        value = project_stair_behavior(source)
        self.assertEqual(source, before)
        self.assertNotIn("window_slip_any", value["profile"]["columns"])
        self.assertIn("loaded_point_motion_any", value["profile"]["columns"])
        self.assertEqual(value["profile"]["rows"][0][0], "frontier")
        self.assertIn("out of row n", value["profile"]["event_count_scope"])
        self.assertIn("does not prove surface slip", value["semantics"]["limits"])
        self.assertIn("may alternate bodies", value["semantics"]["rules"]["loaded_point_motion_any"])
        events = value["transcripts"][0]["events"]
        self.assertTrue(any(e["code"] == "low_progress" and e["start"] == 20 for e in events))
        self.assertTrue(any(e["code"] == "loaded_point_motion_body" for e in events))
        self.assertFalse(any(e["code"].startswith("slip") for e in events))

    def test_budget_pressure_cannot_erase_every_matched_comparison(self):
        episodes = [episode(i, cell=f"cell-{i//2:03}", reason="success" if i % 2 else "forbidden_contact") for i in range(80)]
        value = project_stair_behavior(full(episodes))
        self.assertEqual(value["profile"]["episode_count"], 80)
        self.assertEqual(value["contrasts"]["matched_group_count"], 40)
        self.assertGreater(value["omitted"]["contrast_rows"], 0)
        self.assertGreaterEqual(len(value["contrasts"]["rows"]), 1)
        self.assertEqual(len(value["contrasts"]["rows"]) + value["omitted"]["contrast_rows"], 40)
        self.assertEqual(len(value["transcripts"]), 2)
        self.assertLessEqual(len(json.dumps(value, separators=(",", ":")).encode()), MAX_PUBLIC_BYTES)

    def test_old_view_is_unchanged_and_comparison_resolves_column_names(self):
        old = legacy_view()
        self.assertEqual(project_stair_behavior(old), old)
        new = project_stair_behavior(full([episode(0)]))
        new["domain"]["checkpoint_hash"] = "b"*64
        original_columns = list(new["profile"]["columns"])
        new["profile"]["columns"] = list(reversed(original_columns))
        new["profile"]["rows"] = [list(reversed(row)) for row in new["profile"]["rows"]]
        diff = compare_stair_behavior(old, new, expected_parent_checkpoint_hash="a"*64)
        self.assertEqual(diff["status"], "available")
        self.assertIn("window_slip_any", diff["not_compared_columns"])
        self.assertNotIn("window_slip_any", diff["columns"])
        self.assertIn("loaded_point_motion_any", diff["columns"])
        self.assertTrue(all(value == 0 for value in diff["rows"][0]["rate_delta"]))
        self.assertEqual(project_stair_behavior(old), old)

    def test_motion_representative_covers_modal_conditions_before_duration(self):
        rows = [episode(i) for i in range(5)] + [episode(5, reason="success")]
        for index, row in enumerate(rows[:5]):
            row["steps"] = row["coverage"]["last_step"] = 100 + index*10
        # The length median has a rare condition combination; it must not stand
        # for the other four. Selection is independent of any episode ID.
        rows[2]["before_terminal"]["tilt"] = False
        rows[2]["events"] = [e for e in rows[2]["events"] if e["code"] != "tilt"]
        source = motion_full(rows)
        result = project_stair_behavior(source)
        first = result["transcripts"][0]
        self.assertEqual(first["episode_id"], "r0.e1")
        self.assertEqual(first["process_selection"], {"tilt": True, "low_progress": True, "pattern_n": 4, "group_n": 5})
        self.assertEqual(project_stair_behavior(motion_full(list(reversed(rows)))), result)
        self.assertIn("not full timeline", result["omitted"]["selection"])
        old = project_stair_behavior(full(rows))
        self.assertEqual(old["transcripts"][0]["episode_id"], "r0.e2")
        self.assertNotIn("root_motion", old["transcripts"][0])
        self.assertEqual(project_stair_behavior(old), old)
        diff = compare_stair_behavior(old, result, expected_parent_checkpoint_hash="a"*64)
        self.assertEqual(diff["status"], "not_comparable")
        self.assertEqual(diff["fields"], ["rule_version"])

    def test_motion_budget_keeps_each_failure_stratum_and_same_group_ranges(self):
        rows = []
        for stratum in ("frontier", "height", "rough", "tread", "joint", "phase"):
            for cell_index in range(8):
                for reason in ("forbidden_contact", "forbidden_contact", "success"):
                    row = episode(len(rows), cell=f"{stratum}-{cell_index}", reason=reason)
                    row["stratum"] = stratum
                    rows.append(row)
        source = motion_full(rows)
        source["episodes"][0]["root_motion"]["extrema"]["pitch_rad"] = [-1.3, 30, .6, 40]
        result = project_stair_behavior(source)
        contrasts = result["contrasts"]
        groups = [dict(zip(contrasts["columns"], row)) for row in contrasts["rows"]]
        self.assertEqual({row["stratum"] for row in groups}, {row["stratum"] for row in rows})
        self.assertGreater(result["omitted"]["contrast_rows"], 0)
        totals = result["profile"]["stratum_totals"]
        self.assertEqual(sum(dict(zip(totals["columns"], row))["n"] for row in totals["rows"]), 144)
        frontier = next(row for row in groups if row["stratum"] == "frontier")
        failed = dict(zip(contrasts["side_columns"], frontier["failed"]))
        success = dict(zip(contrasts["side_columns"], frontier["success"]))
        self.assertEqual(failed["pitch_rad_range"], [-1.3, .6])
        self.assertEqual(success["pitch_rad_range"], [-.2, .1])
        self.assertEqual((failed["n"], success["n"]), (2, 1))
        self.assertFalse(any(c.startswith("window_") for c in result["profile"]["columns"]))
        self.assertLessEqual(len(json.dumps(result, separators=(",", ":")).encode()), MAX_PUBLIC_BYTES)
        self.assertIn("not typical or a shared sequence", contrasts["scope"])

    def test_motion_columns_and_missing_success_are_explicit(self):
        result = project_stair_behavior(motion_full([episode(0)]))
        self.assertEqual(result["schema_version"], MOTION_PUBLIC_SCHEMA)
        contrasts = result["contrasts"]
        group = dict(zip(contrasts["columns"], contrasts["rows"][0]))
        success = dict(zip(contrasts["side_columns"], group["success"]))
        self.assertEqual(group["status"], "missing_same_cell_run_success")
        for key in ("max_x_retreat_m", "roll_rad_range", "pitch_rad_range"):
            self.assertIsNone(success[key])
        for values in contrasts["rows"]:
            row = dict(zip(contrasts["columns"], values))
            row["failed"].reverse()
            row["success"].reverse()
        contrasts["side_columns"].reverse()
        contrasts["columns"].reverse()
        for values in contrasts["rows"]:
            values.reverse()
        self.assertEqual(project_stair_behavior(result), result)


if __name__ == "__main__":
    unittest.main()
